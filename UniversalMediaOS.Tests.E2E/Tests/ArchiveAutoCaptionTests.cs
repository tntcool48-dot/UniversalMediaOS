namespace UniversalMediaOS.Tests.E2E.Tests;

/// <summary>Item shapes and caption text observed on archive.org on October 24, 2026, trimmed. Archive's
/// machine speech-recognition captions (name.asr.srt) are made from one original file and written in
/// centiseconds without carrying (",100" is one second). The user decided they are offered, marked
/// auto-generated, only after language and cut-timing checks; captions timed to another cut are not.</summary>
public sealed class ArchiveAutoCaptionTests
{
    // HisGirlFriday1940_201505: first cues, a ",100" overflow cue and the zero-length final cue.
    private const string HisGirlFridayCaptions = """
        1
        00:01:02,83 --> 00:01:08,92
        Mean renewed. Before you think you

        2
        00:01:09,65 --> 00:01:16,57
        think you were the right. Thing polls
        close you just like you almost

        3
        00:01:57,60 --> 00:02:01,100
        anybody just the boring old age. Of the.

        1287
        01:31:40,72 --> 01:31:40,72
        I

        """;

    [Fact]
    public async Task MachineCaptionsOfTheSelectedFileAreOfferedAsEnglishAutoGenerated()
    {
        AudiovisualSource source = Assert.Single(await FindAsync("HisGirlFriday1940_201505", "eng",
            [File("His Girl Friday (1940).asr.srt", "original", null, null),
             File("His Girl Friday (1940).mp4", "original", null, "5517.51"),
             File("His Girl Friday (1940).ogv", "derivative", "His Girl Friday (1940).mp4", "5517.48")],
            ("His Girl Friday (1940).asr.srt", HisGirlFridayCaptions)));

        MediaSubtitleTrack caption = Assert.Single(source.Subtitles);
        Assert.Equal("English (auto-generated)", caption.Label);
        Assert.Equal("en", caption.Language);
        Assert.True(caption.IsAutoGenerated);
        Assert.False(caption.IsDefault);
        Assert.Equal("https://archive.example/download/HisGirlFriday1940_201505/His%20Girl%20Friday%20%281940%29.asr.srt",
            caption.Url);
        Assert.Equal("""
            WEBVTT

            00:01:02.830 --> 00:01:08.920
            Mean renewed. Before you think you

            00:01:09.650 --> 00:01:16.570
            think you were the right. Thing polls
            close you just like you almost

            00:01:57.600 --> 00:02:02.000
            anybody just the boring old age. Of the.


            """.ReplaceLineEndings("\n"), caption.InlineVtt);
    }

    [Fact]
    public async Task CaptionsOfTheDerivativesOriginalAreOfferedWithoutADeclaredLanguage()
    {
        AudiovisualSource source = Assert.Single(await FindAsync("Detour", null,
            [File("Detour.MPEG", "original", null, "4058.25"), File("Detour.asr.srt", "original", null, null),
             File("Detour.mp4", "derivative", "Detour.MPEG", "4058.32")],
            ("Detour.asr.srt", "1\n00:00:10,52 --> 00:00:16,56\nMan. Married\n\n660\n01:07:33,60 --> 01:07:37,46\nOne.\n")));

        MediaSubtitleTrack caption = Assert.Single(source.Subtitles);
        Assert.Equal("Auto-generated (language not declared)", caption.Label);
        Assert.Equal("", caption.Language);
        Assert.True(caption.IsAutoGenerated);
        Assert.Contains("01:07:33.600 --> 01:07:37.460\nOne.", caption.InlineVtt);
    }

    [Fact]
    public async Task CaptionsTranscribedFromAnotherFileAreNotOffered()
    {
        // Night.Of.The.Living.Dead_1080p: the captions come from the DVD originals; the selected file is the PS3 encode.
        AudiovisualSource source = Assert.Single(await FindAsync("Night.Of.The.Living.Dead_1080p", "English",
            [File("NightOfTheLivingDead_DVD5.asr.srt", "original", null, null),
             File("NightOfTheLivingDead_DVD5.mpg", "original", null, "5752.12"),
             File("NightOfTheLivingDead_PS3.mp4", "original", null, "5752.81")]));

        Assert.EndsWith("/NightOfTheLivingDead_PS3.mp4", source.Location.AbsoluteUri, StringComparison.Ordinal);
        Assert.Empty(source.Subtitles);
    }

    [Fact]
    public async Task CaptionRunningPastTheSelectedFileIsTimedToAnotherCut()
    {
        AudiovisualSource source = Assert.Single(await FindAsync("short-cut", "eng",
            [File("film.asr.srt", "original", null, null), File("film.mp4", "original", null, "3600")],
            ("film.asr.srt", "1\n00:00:10,52 --> 00:00:16,56\nOpening.\n\n2\n01:10:00,00 --> 01:10:04,00\nLater scene.\n")));
        Assert.Empty(source.Subtitles);
    }

    [Fact]
    public async Task ReleaseSubtitlesWithoutAKnownSourceFileAreNotOffered()
    {
        // metropolis_202511 lists seven release subtitle files for other restorations of the film.
        AudiovisualSource source = Assert.Single(await FindAsync("metropolis_202511", "ger",
            [File("Metropolis_(2010).srt", "original", null, null), File("Metropolis_1926_sub-english.srt", "original", null, null),
             File("Metropolis .mp4", "original", null, "8907.89")]));
        Assert.Empty(source.Subtitles);
    }

    [Fact]
    public async Task MatroskaFileKeepsItsOwnCaptionTracks()
    {
        // A provider caption list replaces the embedded tracks in the caption menu.
        AudiovisualSource source = Assert.Single(await FindAsync("mkv-item", "eng",
            [File("film.asr.srt", "original", null, null), File("film.mkv", "original", null, "5400")]));
        Assert.Empty(source.Subtitles);
    }

    [Theory]
    [InlineData("<html><body>Not found</body></html>")]
    [InlineData("")]
    public async Task UnusableCaptionResponseStillOffersTheFilm(string response)
    {
        AudiovisualSource source = Assert.Single(await FindAsync("film-item", "eng",
            [File("film.asr.srt", "original", null, null), File("film.mp4", "original", null, "5400")],
            ("film.asr.srt", response)));
        Assert.Empty(source.Subtitles);
    }

    [Fact]
    public void AutoGeneratedCaptionIsNeverTurnedOnWithoutTheViewersChoice()
    {
        var automatic = new MediaSubtitleTrack("https://archive.example/a.asr.srt", "English (auto-generated)", "en")
            { IsAutoGenerated = true };
        var human = new MediaSubtitleTrack("https://cdn.example/fr.vtt", "French", "fr");

        Assert.Null(PlaybackTrackOption.AutomaticExternalCaption(PlaybackTrackOption.ExternalCaptions([automatic])));
        Assert.Equal(human.Url, PlaybackTrackOption.AutomaticExternalCaption(
            PlaybackTrackOption.ExternalCaptions([automatic, human]))!.Subtitle!.Url);
        // It remains a menu choice.
        Assert.Equal("English (auto-generated)", Assert.Single(PlaybackTrackOption.ExternalCaptions([automatic])).Label);
    }

    private static string File(string name, string source, string? original, string? length) =>
        JsonSerializer.Serialize(new Dictionary<string, string?>
        {
            ["name"] = name, ["source"] = source, ["original"] = original, ["length"] = length,
            ["format"] = Path.GetExtension(name).ToLowerInvariant() switch
            {
                ".srt" => "SubRip", ".mpg" or ".mpeg" => "MPEG2", ".mkv" => "Matroska", ".ogv" => "Ogg Video", _ => "MPEG4"
            }
        }.Where(pair => pair.Value != null).ToDictionary());

    private static async Task<IReadOnlyList<AudiovisualSource>> FindAsync(string identifier, string? language,
        string[] files, params (string Name, string Body)[] captions)
    {
        string languageField = language == null ? "" : $",\"language\":{JsonSerializer.Serialize(language)}";
        var responses = new Dictionary<string, string>
        {
            ["/advancedsearch.php"] = $$$"""{"response":{"docs":[{"identifier":"{{{identifier}}}","title":"Example Film","year":1940}]}}""",
            ["/metadata/" + identifier] = $$"""
                {"metadata":{"identifier":"{{identifier}}","title":"Example Film","year":"1940","subject":["Feature films"]{{languageField}}},
                 "files":[{{string.Join(",", files)}}]}
                """
        };
        foreach (var caption in captions) responses[$"/download/{identifier}/{caption.Name}"] = caption.Body;
        var handler = new Responses(responses);
        using var http = new HttpClient(handler);
        var provider = new InternetArchiveSourceProvider(new AudiovisualOptions
        {
            InternetArchiveBaseUri = new Uri("https://archive.example/")
        }, new ProviderRequestCoordinator(http));
        var sources = await provider.FindSourcesAsync(new AudiovisualIdentity
        {
            Kind = AudiovisualMediaKind.Movie, ContentForm = AudiovisualContentForm.Feature, Title = "Example Film", Year = 1940
        }, AudiovisualUnit.Feature);
        // A caption from another file or cut must not even be requested.
        Assert.Empty(handler.Unexpected);
        return sources;
    }

    private sealed class Responses(Dictionary<string, string> responses) : HttpMessageHandler
    {
        public List<string> Unexpected { get; } = [];

        protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken token)
        {
            token.ThrowIfCancellationRequested();
            if (!responses.TryGetValue(Uri.UnescapeDataString(request.RequestUri!.AbsolutePath), out string? body))
            {
                lock (Unexpected) Unexpected.Add(request.RequestUri.AbsoluteUri);
                return Task.FromResult(new HttpResponseMessage(HttpStatusCode.NotFound));
            }
            return Task.FromResult(new HttpResponseMessage(HttpStatusCode.OK)
            {
                Content = new StringContent(body, Encoding.UTF8, "text/plain")
            });
        }
    }
}
